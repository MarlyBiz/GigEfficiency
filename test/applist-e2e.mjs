// 412 px: Settings > Per app: add Instacart + custom app, remove Lyft (confirm), Save; history untouched;
// Edit Shift's "+ Add app" offers the same list. Usage: node test/applist-e2e.mjs <url> <shot-prefix>
import { chromium } from '/tmp/pw/node_modules/playwright-core/index.mjs';
const [url, prefix] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const p = await (await b.newContext({ viewport: { width: 412, height: 900 }, timezoneId: 'America/New_York' })).newPage();
const errs = [], out = {};
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(2500);
await p.evaluate(() => {
  localStorage.clear(); localStorage.setItem('gig_tracker_has_onboarded', 'true'); localStorage.setItem('gig_tracker_samples_seeded', 'true');
  const st = new Date('2026-10-27T16:00:00').getTime();
  localStorage.setItem('gig_tracker_history_records', JSON.stringify([{ id: 'd1', dateStr: '2026-10-27', startTime: st, endTime: st + 5 * 3600e3, totalSeconds: 18000, workSeconds: 14400, totalMiles: 75, workMiles: 65, platformEarnings: [{ id: 'uber', name: 'Uber Rides', amount: 95 }, { id: 'lyft', name: 'Lyft', amount: 45 }], bonusEarnings: [], totalEarnings: 140, dollarsPerHourTotal: 28, dollarsPerHourWork: 35, dollarsPerMileTotal: 1.87, dollarsPerMileWork: 2.15, notes: '', createdAt: 1 }]));
});
await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(2000);
const histBefore = await p.evaluate(() => localStorage.getItem('gig_tracker_history_records'));
await p.click('[aria-label="Settings"]');
const sec = p.locator('[data-testid="cutoff-settings"]');
await sec.locator('button:has-text("Add app")').click();
out.suggestions = await p.locator('[aria-label="App to add"] option').allTextContents();
await p.selectOption('[aria-label="App to add"]', 'Instacart');
await p.click('[data-testid="add-app-form"] button:text-is("Add")');
await sec.locator('button:has-text("Add app")').click();
await p.selectOption('[aria-label="App to add"]', '__custom__');
await p.fill('[aria-label="Custom app name"]', 'Roadie');
await p.click('[data-testid="add-app-form"] button:text-is("Add")');
await sec.locator('button:has-text("Add app")').click();
await p.selectOption('[aria-label="App to add"]', '__custom__');
await p.fill('[aria-label="Custom app name"]', 'roadie');
await p.click('[data-testid="add-app-form"] button:text-is("Add")');
out.dupError = await sec.locator('[role="alert"]').innerText();
await p.click('[aria-label="Cancel adding app"]');
await p.click('[aria-label="Remove Lyft"]');
out.confirmText = await p.locator('[data-testid="confirm-remove-app"]').innerText();
await sec.scrollIntoViewIfNeeded();
await sec.locator('span:text-is("Per app (weekly view & closeouts)")').scrollIntoViewIfNeeded();
await p.screenshot({ path: `${prefix}-per-app-settings.png` });
await p.click('[data-testid="confirm-remove-app"] button:text-is("Remove")');
out.rows = await sec.locator('[data-testid="cutoff-app-row"]').allInnerTexts();
await p.click('button:has-text("Save Settings")');
const st = await p.evaluate(() => JSON.parse(localStorage.getItem('gig_tracker_settings')));
out.savedApps = st.defaultPlatforms;
out.savedRules = Object.fromEntries(Object.entries(st.cutoffs.apps).map(([k, v]) => [k, `${v.dayMinutes}/${v.weekStartDay}/${v.weekStartMinutes}`]));
out.historyUntouched = histBefore === await p.evaluate(() => localStorage.getItem('gig_tracker_history_records'));
// History still shows the Lyft shift; Edit Shift offers the same list
await p.locator('button:visible').filter({ hasText: /^\s*History\s*$/ }).first().click();
await p.click('button:has-text("Edit")');
out.editRows = await p.locator('[data-testid="app-rows"] > div').allInnerTexts();
await p.click('[data-testid="app-rows"] button:has-text("Add app")');
out.editOptions = await p.locator('[aria-label="Choose app"] option').allTextContents();
out.errs = errs;
console.log(JSON.stringify(out, null, 1));
await b.close();
